#!/usr/bin/env python3
"""检查裁判协议布局，以及所选板级或整车配置实际链接的模块。"""
import argparse
from pathlib import Path
import subprocess
import tempfile

import yaml

ROOT = Path(__file__).resolve().parents[2]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--preset", choices=("Debug", "Release"), default="Debug")
args = parser.parse_args()

# Run the upstream layout assertions unchanged, on the host.
referee = ROOT / "Modules/HFUT-WDR/Referee"
with tempfile.TemporaryDirectory(prefix="wdr-referee-layout-") as temp:
    executable = Path(temp) / "types_test"
    subprocess.run(["g++", "-std=c++20", "-Wall", "-Wextra", "-Werror",
                    "-I" + str(referee), str(referee / "tests/types_test.cpp"),
                    "-o", str(executable)], check=True)
    subprocess.run([str(executable)], check=True)

header = (ROOT / "User/xrobot_main.hpp").read_text()
selected = header.splitlines()[0].removeprefix(
    '// Generated by `xrobot gen` from ').split(';')[0]
assert selected in {"User/xrobot.yaml", "User/RobotConfig/sentry_remote.yaml"}, selected
config = yaml.safe_load((ROOT / selected).read_text())
elf = ROOT / "build" / args.preset / "wdr_xrobot_dmmc02_framework.elf"
symbols = subprocess.check_output(["arm-none-eabi-nm", "-C", str(elf)], text=True)
if selected == "User/RobotConfig/sentry_remote.yaml":
    for name in ("Gimbal::ThreadFunc", "DualYaw::ControlLoop", "Pitch::ControlLoop",
                 "Launcher::Update", "Chassis<wdr_chassis::Control>", "PowerControl::Calculate"):
        assert name in symbols, f"整车固件缺少模块符号: {name}"
    gimbal = next(m for m in config["modules"] if m["id"] == "gimbal")
    assert next(a["param"] for a in gimbal["args"] if "param" in a)["pitch"]["zero"] == 0
    print(f"PASS: referee layout and full sentry remote firmware ({args.preset})")
    raise SystemExit(0)

# 板级配置仍保持隔离；整车启用由独立完整配置声明。
assert {m["module"] for m in config["modules"]} == {
    "HFUT-WDR/BuzzerAlarm", "HFUT-WDR/BMI088", "HFUT-WDR/BoardAttitude"}, "Unexpected default activation"
for name in ("RMMotor", "DMMotor", "DR16", "Referee", "HostData", "CMD",
             "SharedTopic", "SharedTopicClient", "I6x", "EventBinder", "DmImu", "Chassis", "PowerControl", "DualYaw", "Pitch", "Gimbal"):
    assert name + "::" not in symbols, f"Inactive module linked into firmware: {name}"
assert "wdr_chassis::Control::" not in symbols, "Inactive chassis controller linked into firmware"
assert "wdr_chassis::PowerControl::" not in symbols, "Inactive power controller linked into firmware"
assert "wdr_chassis::SuperCap::" not in symbols, "Inactive supercap linked into firmware"
assert "wdr_control::PID::" not in symbols, "Inactive control PID linked into firmware"
assert "XRobotCompileCheck" not in symbols, "Compile check linked into firmware"
print(f"PASS: upstream referee layout; {args.preset} board-only config and ELF isolation")
